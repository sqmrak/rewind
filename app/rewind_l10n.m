/* no stored preference yet: read the device's own language instead of
   forcing english on a russian system */
static NSString *RewindSystemLanguageCode(void) {
    for (NSString *preferred in [NSLocale preferredLanguages]) {
        if ([preferred hasPrefix:@"ru"]) return @"ru";
        if ([preferred hasPrefix:@"en"]) return @"en";
    }
    return @"en";
}

NSString *RewindLanguageCode(void) {
    NSString *code = [[NSUserDefaults standardUserDefaults]
                      objectForKey:REWIND_LANGUAGE_DEFAULTS_KEY];
    if ([code isEqualToString:@"ru"] || [code isEqualToString:@"en"]) return code;
    return RewindSystemLanguageCode();
}

void RewindSetLanguageCode(NSString *code) {
    if (![code isEqualToString:@"ru"] && ![code isEqualToString:@"en"])
        code = @"en";
    [[NSUserDefaults standardUserDefaults] setObject:code
                                              forKey:REWIND_LANGUAGE_DEFAULTS_KEY];
    [[NSUserDefaults standardUserDefaults] synchronize];
    [[NSNotificationCenter defaultCenter]
     postNotificationName:REWIND_LANGUAGE_DID_CHANGE_NOTIFICATION object:nil];
}

BOOL RewindLanguageIsRussian(void) {
    return [RewindLanguageCode() isEqualToString:@"ru"];
}

NSString *RewindL(NSString *key) {
    if (!key.length) return @"";
    NSString *value = [RewindTableForCode(RewindLanguageCode()) objectForKey:key];
    if (value.length) return value;
    value = [RewindTableForCode(@"en") objectForKey:key];
    return value.length ? value : key;
}
