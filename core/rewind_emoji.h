#ifndef REWIND_EMOJI_H
#define REWIND_EMOJI_H

#include <stddef.h>
#include <stdint.h>

#define REWIND_EMOJI_STATUS_FULL 0     /* the form the keyboards send */
#define REWIND_EMOJI_STATUS_MINIMAL 1
#define REWIND_EMOJI_STATUS_BARE 2     /* a text style code point that a sender left without the emoji selector */
#define REWIND_EMOJI_NO_IMAGE 0xFFFFu
#define REWIND_EMOJI_GROUPS 9

typedef struct rewind_emoji_entry {
    uint32_t offset;        /* of the first code point in rewind_emoji_points */
    uint8_t length;         /* code points */
    uint8_t status;
    uint8_t version;        /* the Emoji version times ten: 6 is Emoji 0.6, 131 is Emoji 13.1 */
    uint8_t group;          /* index into the picker groups */
    uint16_t canonical;     /* the fully qualified entry this one draws as; its own index when it is one */
    uint16_t image;         /* index into the picture pack, REWIND_EMOJI_NO_IMAGE when it has none */
    uint8_t tone;           /* carries a skin tone, left out of the picker grid */
} rewind_emoji_entry;

/* generated by tools/make_emoji.py; entries are sorted by their code points */
extern const uint32_t rewind_emoji_points[];
extern const rewind_emoji_entry rewind_emoji_entries[];
extern const uint32_t rewind_emoji_first_points[];
extern const uint16_t rewind_emoji_picker[];
extern const uint16_t rewind_emoji_group_start[];
extern const size_t rewind_emoji_entry_count;
extern const size_t rewind_emoji_first_count;
extern const size_t rewind_emoji_picker_count;
extern const size_t rewind_emoji_image_count;
extern const size_t rewind_emoji_longest;

typedef struct rewind_emoji_span {
    size_t start;           /* in UTF-16 units of the scanned text */
    size_t length;
    uint16_t entry;         /* the canonical entry, whatever form the text used */
} rewind_emoji_span;

/* the index of the entry with exactly these code points; 0 when there is none, 1 when found */
int rewind_emoji_find(const uint32_t *points, size_t count, size_t *index);

/* finds the emoji in UTF-16 text, longest sequence first, left to right, at most cap spans */
size_t rewind_emoji_scan(const uint16_t *text, size_t length, rewind_emoji_span *spans, size_t cap);
/* one complete emoji and no surrounding text; entry is initialized even when no match exists */
int rewind_emoji_single(const uint16_t *text, size_t length, size_t *entry);

/* an entry as UTF-16, for typing it into a message; returns the units written, zero when cap is too small */
size_t rewind_emoji_encode(size_t entry, uint16_t *out, size_t cap);

/* alpha bounds ignore faint shadows when fitting emoji from different font canvases */
int rewind_emoji_alpha_bounds(const uint8_t *pixels, size_t capacity, size_t width, size_t height,
                              size_t stride, size_t bounds[4]);

#endif
